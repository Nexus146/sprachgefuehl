    /** Einzelwörter, die aus zwei Teilen bestehen, werden zusätzlich als Paar erkannt. */
    private val phrases: List<Pair<String, String>> = entries
        .filterKeys { it.contains(' ') }
        .map { (en, de) -> en to de }
        .sortedByDescending { it.first.length }

    fun of(word: String): String? {
        val clean = word.lowercase()
            .replace('’', '\'')
            .trim()
            .trim('.', ',', '!', '?', ';', ':', '"', '„', '“', '(', ')')
        if (clean.isEmpty()) return null
        entries[clean]?.let { return it }
        // Einfache Plural- und -s-Formen, die im Inhalt vorkommen.
        if (clean.endsWith("s")) entries[clean.dropLast(1)]?.let { return it }
        return null
    }

    /** Die längste passende Wendung am Wortanfang, etwa „how much“ oder „thank you“. */
    fun phraseAt(words: List<String>, index: Int): Pair<String, String>? {
        if (index !in words.indices) return null
        val rest = words.drop(index).joinToString(" ").lowercase()
            .replace('’', '\'')
        return phrases.firstOrNull { rest == it.first || rest.startsWith(it.first + " ") }
    }

    val size: Int get() = entries.size
